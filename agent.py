
import os

from dotenv import load_dotenv
import requests

from github import Github


OLLAMA_URL = "http://localhost:11434/api/generate"
MODEL_NAME = "mistral"


load_dotenv()
GITHUB_TOKEN = os.getenv("GITHUB_TOKEN")
REPO_NAME = "ssalmarezgui/algo-visualizer"

if not GITHUB_TOKEN:
    raise ValueError("⚠️ ERREUR : Le GITHUB_TOKEN est introuvable dans le fichier .env")


def generer_code_algorithme(nom_algo):
    prompt = f"""
    Tu es un développeur expert en TypeScript et React. 
    Ton travail est de créer un nouveau module d'algorithme de tri pour notre application web "AlgoVisualizer".
    
    Le fichier doit être 100% en TypeScript et respecter EXACTEMENT cette structure :

    1. Importer les types nécessaires :
       import type {{ AlgorithmInfo, SortingStep }} from '../types';

    2. Exporter un objet de métadonnées nommé `{nom_algo.lower().replace(' ', '')}Info` de type `AlgorithmInfo` :
       export const {nom_algo.lower().replace(' ', '')}Info: AlgorithmInfo = {{
         id: '{nom_algo.lower().replace(' ', '')}',
         name: '{nom_algo}',
         description: 'Courte description de l\\'algorithme.',
         timeComplexity: 'O(...)',
         spaceComplexity: 'O(...)',
       }};

    3. Exporter un tableau de chaînes de caractères contenant le code source Python de l'algorithme ligne par ligne, nommé `{nom_algo.upper().replace(' ', '_')}_CODE_LINES`.

    4. Exporter une fonction de tri qui prend un tableau de nombres `array: number[]` et retourne un tableau de `SortingStep[]`, avec le suivi des lignes actives (`activeLine`).

    Règles strictes :
    - Renvoie UNIQUEMENT le code TypeScript brut, sans texte autour, sans balises markdown ```typescript.
    - Le code doit être propre et sans erreurs de syntaxe.

    Écris le module complet pour l'algorithme : {nom_algo}

    """

    code_genere = interroger_ollama(prompt)

    return code_genere



def interroger_ollama(prompt):
    print(f" L'agent réfléchit avec Ollama ({MODEL_NAME})...") 

    payload = {
        "model": MODEL_NAME,
        "prompt": prompt,
        "stream": False
    }


    response = requests.post(OLLAMA_URL, json = payload)

    if response.status_code == 200:
        return response.json().get("response", "")

    else:
        raise Exception(f"Erreur Ollama: {response.text}")


def creer_pull_request_github(nom_algo, code_genere):
    print(f" Connexion a l'API GitHub")

    g = Github(GITHUB_TOKEN)
    repo = g.get_repo(REPO_NAME)


    # NOM DE NOUVELLE BRANCHE
    branche_source = "main"
    nouvelle_branche = f"feature/add-{nom_algo.lower().replace(' ', '-')}"

    # RECUPERE LE COMMIT DE REFERENCE DE MAIN
    sb = repo.get_branch(branche_source)

    repo.create_git_ref(ref = f"refs/heads/{nouvelle_branche}", sha = sb.commit.sha)


    print(f" Branche '{nouvelle_branche}' créée")


    # CREER LE FICHIER DE L'ALGORITHME DANS src/algorithms/

    chemin_fichier = f"src/algorithms/{nom_algo.lower().replace(' ', '')}Sort.ts"
    message_commit = f"add {nom_algo} generated by local Agenetic AI"

    try:
        repo.create_file(
            path = chemin_fichier,
            message = message_commit,
            content = code_genere,
            branch = nouvelle_branche
        )

        print(f" Fichier {chemin_fichier} ajouté sur la branche.")

    except Exception as e :
        print(f" Le fichier existe peut-être déjà : {e}")
        return

    # OUVRIR LA PULL REQUEST

    titre_pr = f" [Agent AI] Ajout de l'algorithme : {nom_algo}"

    corps_pr = f"Bonjour !\n\nCet algorithme ({nom_algo}) a été suggéré par un visiteur et généré automatiquement par l'Agent IA local.\n\nVeuillez vérifier le code avant de merger."

    pr = repo.create_pull(
        title = titre_pr,
        body = corps_pr,
        head = nouvelle_branche,
        base = branche_source
    )
    print(f" Pull Request créée avec succès : {pr.html_url}")

if __name__ == "__main__":
    algorithme_demande = "Merge Sort"

    print(f"Lancement de l'agent pour : {algorithme_demande}")

    code_ia = generer_code_algorithme(algorithme_demande)

    if code_ia:
        creer_pull_request_github(algorithme_demande, code_ia)


    