import os
from dotenv import load_dotenv
import requests
from github import Github

OLLAMA_URL = "http://localhost:11434/api/generate"
MODEL_NAME = "mistral"

load_dotenv()
GITHUB_TOKEN = os.getenv("GITHUB_TOKEN")
REPO_NAME = "ssalmarezgui/algo-visualizer"

if not GITHUB_TOKEN:
    raise ValueError("⚠️ ERREUR : Le GITHUB_TOKEN est introuvable dans le fichier .env")


def interroger_ollama(prompt):
    print(f"🤖 L'agent réfléchit avec Ollama ({MODEL_NAME})...") 
    payload = {
        "model": MODEL_NAME,
        "prompt": prompt,
        "stream": False
    }
    response = requests.post(OLLAMA_URL, json=payload)
    if response.status_code == 200:
        return response.json().get("response", "")
    else:
        raise Exception(f"Erreur Ollama: {response.text}")


def generer_code_algorithme(nom_algo):
    prompt = f"""
    Tu es un développeur expert en TypeScript et React. 
    Ton travail est de créer un nouveau module d'algorithme de tri pour notre application web "AlgoVisualizer".
    
    Le fichier doit être 100% en TypeScript et respecter EXACTEMENT cette structure :

    1. Importer les types nécessaires :
       import type {{ AlgorithmInfo, SortingStep }} from '../types';

    2. Exporter un objet de métadonnées nommé `{nom_algo.lower().replace(' ', '')}Info` de type `AlgorithmInfo` :
       export const {nom_algo.lower().replace(' ', '')}Info: AlgorithmInfo = {{
         id: '{nom_algo.lower().replace(' ', '')}',
         name: '{nom_algo}',
         description: 'Description de l\\'algorithme.',
         timeComplexity: 'O(...)',
         spaceComplexity: 'O(...)',
       }};

    3. Exporter un tableau de chaînes de caractères contenant le code source de l'algorithme ligne par ligne, nommé `{nom_algo.toUpperCase().replace(' ', '_')}_CODE_LINES`.

    4. Exporter une fonction de tri qui prend un tableau de nombres `array: number[]` et retourne un tableau de `SortingStep[]`, avec le suivi des lignes actives (`activeLine`).

    Règles strictes :
    - Renvoie UNIQUEMENT le code TypeScript pur, sans texte explicatif, sans balises markdown ```typescript.
    """
    code_brut = interroger_ollama(prompt)
    return code_brut.replace("```typescript", "").replace("```ts", "").replace("```", "").strip()


def modifier_registry_avec_ia(nom_algo, contenu_actuel_registry):
    prompt = f"""
    Tu es un développeur expert en TypeScript. 
    Voici le contenu actuel du fichier 'registry.ts' de notre application React :

    {contenu_actuel_registry}

    Je viens d'ajouter un nouvel algorithme nommé '{nom_algo}'. 
    Son identifiant est '{nom_algo.lower().replace(' ', '')}'.
    Le fichier du module s'appelle './{nom_algo.lower().replace(' ', '')}'.
    Les exports à importer sont : `{nom_algo.lower().replace(' ', '')}Info`, `{nom_algo.toUpperCase().replace(' ', '_')}_CODE_LINES`, et `{nom_algo.lower().replace(' ', '')}Sort`.

    Modifie le fichier 'registry.ts' pour :
    1. Importer ce nouveau module en haut.
    2. L'ajouter dans le tableau `SORTING_ALGORITHMS`.
    3. L'ajouter dans l'objet `ALGORITHM_REGISTRY`.

    Règles strictes :
    - Renvoie UNIQUEMENT le code TypeScript complet et mis à jour du fichier registry.ts.
    - Pas de texte autour, pas de balises markdown ```typescript.
    """
    code_brut = interroger_ollama(prompt)
    return code_brut.replace("```typescript", "").replace("```ts", "").replace("```", "").strip()


def creer_pull_request_github(nom_algo):
    print("🐙 Connexion à l'API GitHub...")
    g = Github(GITHUB_TOKEN)
    repo = g.get_repo(REPO_NAME)

    branche_source = "main"
    nouvelle_branche = f"feature/add-{nom_algo.lower().replace(' ', '-')}"

    sb = repo.get_branch(branche_source)

    # Vérifier si la branche existe déjà pour éviter l'erreur 422
    try:
        repo.get_git_ref(f"heads/{nouvelle_branche}")
        print(f"⚠️ La branche '{nouvelle_branche}' existe déjà, on l'utilise.")
    except:
        repo.create_git_ref(ref=f"refs/heads/{nouvelle_branche}", sha=sb.commit.sha)
        print(f"🌿 Branche '{nouvelle_branche}' créée.")

    # 1. Générer le code du nouvel algorithme via Ollama
    print(f"🚀 Génération du code pour : {nom_algo}")
    code_algo = generer_code_algorithme(nom_algo)

    mots = nom_algo.lower().split()
    nom_fichier = mots[0] + "".join([m.capitalize() for m in mots[1:]])
    chemin_algo = f"src/algorithms/{nom_fichier}.ts"
    message_commit = f"feat: add {nom_algo} generated by local Agentic AI"

    try:
        repo.create_file(
            path=chemin_algo,
            message=message_commit,
            content=code_algo,
            branch=nouvelle_branche
        )
        print(f"📄 Fichier {chemin_algo} ajouté sur la branche.")
    except Exception as e:
        print(f"⚠️ Le fichier existe peut-être déjà : {e}")
        return

    # 2. Lire et modifier registry.ts via l'IA
    print("📝 Mise à jour de src/algorithms/registry.ts via l'IA...")
    file_registry = repo.get_contents("src/algorithms/registry.ts", ref=branche_source)
    contenu_registry = file_registry.decoded_content.decode('utf-8')

    nouveau_registry = modifier_registry_avec_ia(nom_algo, contenu_registry)

    try:
        repo.update_file(
            path="src/algorithms/registry.ts",
            message=f"feat: update registry for {nom_algo}",
            content=nouveau_registry,
            sha=file_registry.sha,
            branch=nouvelle_branche
        )
        print("📄 Fichier registry.ts mis à jour et commité sur la branche.")
    except Exception as e:
        print(f"⚠️ Erreur lors de la mise à jour de registry.ts : {e}")

    # 3. Ouvrir la Pull Request
    titre_pr = f"🤖 [Agent AI] Ajout automatique : {nom_algo}"
    corps_pr = f"Bonjour !\n\nL'Agent IA local a généré le module pour **{nom_algo}** et a mis à jour le registre automatiquement.\n\nVeuillez vérifier le code avant de merger."

    pr = repo.create_pull(
        title=titre_pr,
        body=corps_pr,
        head=nouvelle_branche,
        base=branche_source
    )
    print(f"🎉 Pull Request créée avec succès : {pr.html_url}")


if __name__ == "__main__":
    # Test avec un nouvel algorithme (ex: Quick Sort)
    algorithme_demande = "Quick Sort"
    creer_pull_request_github(algorithme_demande)