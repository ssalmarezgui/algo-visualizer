
import os

from dotenv import load_dotenv
import requests

from github import Github


OLLAMA_URL = "http://localhost:11434/api/generate"
MODEL_NAME = "mistral"


load_dotenv()
GITHUB_TOKEN = os.getenv("GITHUB_TOKEN")
REPO_NAME = "ssalmarezgui/algo-visualizer"

if not GITHUB_TOKEN:
    raise ValueError("⚠️ ERREUR : Le GITHUB_TOKEN est introuvable dans le fichier .env")


def generer_code_algorithme(nom_algo):
    prompt = f"""
    Tu es un compilateur de code et un développeur expert en TypeScript et React. 
    Ton unique tâche est de rédiger le code source d'un module TypeScript pour l'algorithme '{nom_algo}'.

    REGLES ABSOLUES ET NON NEGOCIABLES :
    1. Renvoie UNIQUEMENT du code TypeScript pur. 
    2. INTERDICTION ABSOLUE d'inclure du texte explicatif, de la conversation ou des salutations avant ou après le code.
    3. INTERDICTION ABSOLUE d'utiliser les balises markdown (pas de ```typescript et pas de ```). Le premier caractère de ta réponse DOIT être 'import' et le dernier doit être la dernière accolade '}}'.
    4. La structure du type SortingStep est UNIQUEMENT : {{ array: number[], comparing: number[], swapping: number[], sorted: number[], activeLine: number }}. N'utilise JAMAIS de propriété 'changes'.

    Voici un exemple exact de la structure attendue pour les étapes :
    steps.push({{ array: [...arr], comparing: [j, j + 1], swapping: [], sorted: [...sortedIndices], activeLine: 5 }});

    Rédige le code complet pour : {nom_algo}
    """
    
    code_brut = interroger_ollama(prompt)
    
    code_propre = code_brut.replace("```typescript", "").replace("```ts", "").replace("```", "").strip()
    
    return code_propre



def interroger_ollama(prompt):
    print(f" L'agent réfléchit avec Ollama ({MODEL_NAME})...") 

    payload = {
        "model": MODEL_NAME,
        "prompt": prompt,
        "stream": False
    }


    response = requests.post(OLLAMA_URL, json = payload)

    if response.status_code == 200:
        return response.json().get("response", "")

    else:
        raise Exception(f"Erreur Ollama: {response.text}")


def creer_pull_request_github(nom_algo, code_genere):
    print(f" Connexion a l'API GitHub")

    g = Github(GITHUB_TOKEN)
    repo = g.get_repo(REPO_NAME)


    # NOM DE NOUVELLE BRANCHE
    branche_source = "main"
    nouvelle_branche = f"feature/add-{nom_algo.lower().replace(' ', '-')}"

    # RECUPERE LE COMMIT DE REFERENCE DE MAIN
    sb = repo.get_branch(branche_source)

    repo.create_git_ref(ref = f"refs/heads/{nouvelle_branche}", sha = sb.commit.sha)


    print(f" Branche '{nouvelle_branche}' créée")


    # CREER LE FICHIER DE L'ALGORITHME DANS src/algorithms/

    # Supprime les espaces et met au format propre (ex: Merge Sort -> mergeSort)
    mots = nom_algo.lower().split()
    nom_fichier = mots[0] + "".join([m.capitalize() for m in mots[1:]])
    chemin_fichier = f"src/algorithms/{nom_fichier}.ts"
    message_commit = f"add {nom_algo} generated by local Agenetic AI"

    try:
        repo.create_file(
            path = chemin_fichier,
            message = message_commit,
            content = code_genere,
            branch = nouvelle_branche
        )

        print(f" Fichier {chemin_fichier} ajouté sur la branche.")

    except Exception as e :
        print(f" Le fichier existe peut-être déjà : {e}")
        return

    # OUVRIR LA PULL REQUEST

    titre_pr = f" [Agent AI] Ajout de l'algorithme : {nom_algo}"

    corps_pr = f"Bonjour !\n\nCet algorithme ({nom_algo}) a été suggéré par un visiteur et généré automatiquement par l'Agent IA local.\n\nVeuillez vérifier le code avant de merger."

    pr = repo.create_pull(
        title = titre_pr,
        body = corps_pr,
        head = nouvelle_branche,
        base = branche_source
    )
    print(f" Pull Request créée avec succès : {pr.html_url}")

if __name__ == "__main__":
    algorithme_demande = "Merge Sort"

    print(f"Lancement de l'agent pour : {algorithme_demande}")

    code_ia = generer_code_algorithme(algorithme_demande)

    if code_ia:
        creer_pull_request_github(algorithme_demande, code_ia)


    